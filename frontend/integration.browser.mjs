// Run in the served app: await (await import('./integration.browser.mjs')).verifyIntegration()
export async function verifyIntegration() {
  const checked = [];
  const assert = (condition, message) => {
    if (!condition) throw new Error(message);
    checked.push(message);
  };
  const click = (selector) => {
    const element = document.querySelector(selector);
    if (!element || element.disabled) throw new Error(`Unavailable control: ${selector}`);
    element.click();
  };
  const settled = () => new Promise((resolve) => setTimeout(resolve, 30));
  const action = async (name) => { click(`[data-action="${name}"]`); await settled(); };
  const route = async (name) => { location.hash = name; await settled(); };
  const card = (name) => click(`[data-card-action="${name}"]`);
  const text = () => document.querySelector('#app').textContent;
  const fits = (name) => assert(document.documentElement.scrollWidth <= innerWidth, `${name}: no horizontal overflow`);
  const submit = (name, values) => {
    const form = document.querySelector(`[data-form="${name}"]`);
    for (const [key, value] of Object.entries(values)) form.elements[key].value = value;
    form.requestSubmit();
  };

  await route('home');
  if (document.querySelector('[data-action="logout"]')) await action('logout');
  await route('product/stark');
  assert(!!document.querySelector('[data-action="login"]'), 'Product deep links require demo login');
  await action('login');
  assert(document.querySelectorAll('.bottom-nav button').length === 6, 'Six common menu entries');
  assert(text().includes('8,100,000원'), 'Original demo total assets');
  fits('home');

  await action('cards');
  assert(document.querySelectorAll('.demo-label').length === 1, 'One demo label on cards');
  assert(document.querySelector('.bottom-nav [aria-current]').dataset.action === 'cards', 'Cards menu active');
  card('view-list');
  assert(document.querySelectorAll('.cards-list-item').length === 2, 'Both cards in list');
  card('view-large');
  card('history');
  assert(text().includes('238,500원'), 'Debit monthly total');
  card('overview');
  card('select-stark');
  card('benefits');
  assert(text().includes('연회비'), 'Credit benefits detail');
  card('overview');
  card('manage');
  card('limit');
  assert(text().includes('2,580,000원'), 'Credit remaining limit');
  card('manage');
  fits('card detail');
  card('suspend');
  assert(document.querySelector('dialog').open, 'Native card confirmation dialog');
  card('cancel');
  await settled();
  assert(!document.querySelector('[data-card-action="suspend"]').disabled, 'Cancel leaves card active');
  card('lost');
  card('confirm');
  assert(document.querySelector('[data-card-action="lost"]').disabled, 'Lost card action disabled');
  await action('home');
  await action('cards');
  card('select-stark');
  card('manage');
  assert(document.querySelector('[data-card-action="lost"]').disabled, 'Card status survives menu round trip');
  await action('products');
  assert(document.querySelectorAll('.demo-label').length === 1, 'One demo label on products');
  assert(document.querySelector('.bottom-nav [aria-current]').dataset.action === 'products', 'Products menu active');
  assert(text().includes('전체 상품 5개'), 'Five demo products');
  fits('products');
  click('[data-product-filter="savings"]');
  assert(text().includes('적금 상품 2개'), 'Savings filter');
  click('a[href="#product/stark"]');
  await settled();
  assert(text().includes('연 4.00%'), 'Opening-eligible rate in integrated detail');
  fits('product detail');
  history.back();
  await settled();
  assert(text().includes('적금 상품 2개'), 'Browser back preserves filter');
  history.forward();
  await settled();
  assert(text().includes('가입 조건'), 'Browser forward restores detail');
  await route('product/missing');
  assert(text().includes('상품을 찾을 수 없어요'), 'Unknown product fallback');

  await action('account');
  assert(text().includes('생활비 통장'), 'Original account screen');
  await action('manage');
  submit('rename', { alias: 'QA 통장' });
  await settled();
  assert(text().includes('QA 통장'), 'Original account rename');
  await action('home');
  await action('start-transfer');
  submit('recipient', { number: '110-100-000101' });
  submit('amount', { amount: '50000' });
  await action('to-pin');
  submit('register', { pin: '123456' });
  submit('pin', { pin: '123456' });
  assert(text().includes('데모 이체를 마쳤어요'), 'Original direct transfer PIN flow');
  await action('transfer-close');
  assert(text().includes('8,050,000원'), 'Transfer updates home assets');
  await action('chat');
  submit('chat', { question: '토니에게 5만 원 보내고 싶어' });
  await new Promise((resolve) => setTimeout(resolve, 400));
  assert(text().includes('어느 통장에서'), 'Chat asks for transfer source');
  submit('chat', { question: 'QA 통장' });
  await new Promise((resolve) => setTimeout(resolve, 400));
  const draft = document.querySelector('[data-action^="chat-transfer-"]');
  assert(!!draft, 'Chat creates transfer draft');
  draft.click();
  await settled();
  assert(text().includes('이체 내용을 확인해 주세요'), 'Chat opens shared transfer review');
  await action('to-pin');
  submit('pin', { pin: '123456' });
  assert(text().includes('데모 이체를 마쳤어요'), 'Chat transfer uses registered PIN');
  await action('transfer-close');
  await action('home');
  await action('logout');
  await route('cards');
  assert(!!document.querySelector('[data-action="login"]'), 'Cards route guarded after logout');
  await action('login');
  assert(text().includes('8,100,000원') && !text().includes('QA 통장'), 'Logout resets original demo data');
  await action('cards');
  card('select-stark');
  card('manage');
  assert(!document.querySelector('[data-card-action="lost"]').disabled, 'Logout resets card status');
  await action('products');
  assert(text().includes('전체 상품 5개'), 'Logout resets product filter');
  return { width: innerWidth, checked };
}
